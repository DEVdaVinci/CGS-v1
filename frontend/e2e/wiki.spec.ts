import { expect, test, type Page } from '@playwright/test'

async function openWiki(page: Page) {
  const password = process.env.CGS_E2E_PASSWORD
  if (!password) throw new Error('Set CGS_E2E_PASSWORD for the disposable browser test accounts.')
  await page.goto('/')
  await page.getByLabel('Username').fill('e2e-owner')
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  const name = 'Cedar world ' + crypto.randomUUID().slice(0, 8)
  await page.getByRole('button', { name: 'Create world' }).click()
  await page.getByLabel('World name').fill(name)
  await page.getByRole('button', { name: 'Save world' }).click()
  await page.getByRole('link', { name, exact: true }).click()
  await page.getByRole('link', { name: 'Open Wiki' }).click()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}

async function createEntry(page: Page, name: string, type: string) {
  await page.getByRole('button', { name: 'New entry' }).click()
  const form = page.getByRole('form', { name: 'New entry' })
  await form.getByLabel('Entry name').fill(name)
  await form.getByLabel('Entry type').selectOption({ label: type })
  await form.getByRole('button', { name: 'Save entry' }).click()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}

async function openEntry(page: Page, name: string, type: string) {
  await page.getByRole('navigation', { name: 'Wiki entries' }).getByRole('button', { name: name + ' ' + type, exact: true }).click()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
}

async function fact(page: Page, field: string, value: string, options: {
  reference?: boolean; secret?: boolean; qualifier?: { label: string; entry: string }
} = {}) {
  await page.getByRole('button', { name: 'Record fact', exact: true }).click()
  const form = page.getByRole('form', { name: 'Record fact' })
  await form.getByRole('combobox', { name: 'Field', exact: true }).selectOption({ label: field })
  if (options.reference) await form.getByRole('combobox', { name: 'Value', exact: true }).selectOption({ label: value }, { timeout: 8000 })
  else await form.getByLabel('Value', { exact: true }).fill(value)
  if (options.qualifier) await form.getByRole('combobox', { name: options.qualifier.label, exact: true })
    .selectOption({ label: options.qualifier.entry })
  if (options.secret) await form.getByLabel('Author only').check()
  await form.getByRole('button', { name: 'Save fact' }).click()
  await expect(page.getByRole('region', { name: 'Fact history' })).toBeVisible()
}

