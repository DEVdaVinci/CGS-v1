async function fact(page: Page, field: string, value: string, options: {
  reference?: boolean; choice?: boolean; secret?: boolean; qualifier?: { label: string; entry: string }; citation?: string; from?: number; until?: number
} = {}) {
  await page.getByRole('button', { name: 'Record fact', exact: true }).click()
  const form = page.getByRole('form', { name: 'Record fact' })
  await form.getByRole('combobox', { name: 'Field', exact: true }).selectOption({ label: field })
  if (options.reference || options.choice) {
    await form.getByRole('combobox', { name: 'Value', exact: true }).selectOption({ label: value }, { timeout: 8000 })
  }
  else await form.getByLabel('Value', { exact: true }).fill(value)
  if (options.qualifier) await form.getByRole('combobox', { name: options.qualifier.label, exact: true })
    .selectOption({ label: options.qualifier.entry })
  if (options.citation) await form.getByRole('combobox', { name: 'Source article', exact: true }).selectOption({ label: options.citation })
  if (options.secret) await form.getByLabel('Author only').check()
  const effectiveFrom = form.getByLabel('Effective from')
  if (options.from !== undefined || !(await effectiveFrom.inputValue())) await effectiveFrom.fill(String(options.from ?? 0))
  if (options.until !== undefined) await form.getByLabel('Effective until (optional)', { exact: true }).fill(String(options.until))
  await form.getByRole('button', { name: 'Save fact' }).click()
  await expect(page.getByRole('region', { name: 'Fact history' })).toBeVisible()
  await expect(form).toHaveCount(0)
}

function wikiApi(page: Page) {
  const url = new URL(page.url())
  const [, , worldId] = url.pathname.split('/')
  return url.origin + '/api/v1/worlds/' + worldId + '/wiki'
}

async function readWiki(page: Page, path: string, params: Record<string, string | number> = {}): Promise<WikiView> {
  const response = await page.request.get(wikiApi(page) + path, { params })
  expect(response.ok()).toBeTruthy()
  return await response.json()
}

