test('recovers the same Wiki save after the response is lost and the page refreshes', async ({ page }) => {
  page.setDefaultTimeout(8_000)
  await openWiki(page)
  const keys: string[] = []
  await page.route('**/api/v1/worlds/*/wiki/changes', async (route) => {
    keys.push(route.request().headers()['idempotency-key'])
    if (keys.length === 1) {
      expect((await route.fetch()).status()).toBe(200)
      await route.abort('failed')
    } else {
      await route.continue()
    }
  })
  await page.getByRole('button', { name: 'New entry' }).click()
  await page.getByLabel('Entry name').fill('Recovered record')
  await page.getByRole('button', { name: 'Save entry' }).click()
  await expect(page.getByRole('alert')).toContainText('couldn’t confirm the save')
  await page.reload()
  await page.getByRole('button', { name: 'Retry save' }).click()
  await expect(page.getByRole('heading', { name: 'Recovered record', exact: true })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Wiki entries' }).getByRole('button', { name: 'Recovered record Character' })).toHaveCount(1)
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBe(keys[1])
})

